#!/usr/bin/env bash
# ==============================================================================
# DeloOS / Deloway Desktop Experience - Update & Schema Migration Engine
# Gracefully updates repository, migrates configuration schemas, and reloads shell
# ==============================================================================

set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DELOWAY_DIR="$SCRIPT_DIR"

BOLD='\033[1m'
GREEN='\033[0;32m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

log_info() { echo -e "${BLUE}${BOLD}[INFO]${NC} $1"; }
log_success() { echo -e "${GREEN}${BOLD}[SUCCESS]${NC} $1"; }
log_warn() { echo -e "${YELLOW}${BOLD}[WARNING]${NC} $1"; }
log_error() { echo -e "${RED}${BOLD}[ERROR]${NC} $1"; }

USER_CONFIG="$HOME/.config/deloway/deloway.json"
TEMPLATE_CONFIG="$DELOWAY_DIR/config/deloway.json"
BACKUP_DIR="$HOME/.config/deloway/backups"
UPDATE_OK=true   # cleared by any step that fails, so the summary never over-claims

print_header() {
    echo -e "${CYAN}${BOLD}==> Deloway Update & Schema Migration Engine${NC}"
}

sync_git_repo() {
    log_info "Checking for repository updates..."
    if [ -d "$DELOWAY_DIR/.git" ]; then
        cd "$DELOWAY_DIR"
        local status
        status=$(git status --porcelain || true)
        if [ -n "$status" ]; then
            log_warn "Local repository has uncommitted modifications. Skipping git pull to preserve local edits."
        else
            log_info "Pulling latest upstream changes..."
            git pull --ff-only 2>/dev/null || { log_warn "Could not fast-forward git pull (offline or detached head). Continuing with local version."; UPDATE_OK=false; }
        fi
    fi
}

backup_config() {
    if [ -f "$USER_CONFIG" ]; then
        mkdir -p "$BACKUP_DIR"
        local timestamp
        timestamp=$(date +"%Y%m%d_%H%M%S")
        local backup_file="$BACKUP_DIR/deloway.json.bak.$timestamp"
        cp "$USER_CONFIG" "$backup_file"
        log_success "Configuration backed up to: $backup_file"
        # Keep the 10 most recent backups.
        ls -1t "$BACKUP_DIR"/deloway.json.bak.* 2>/dev/null | tail -n +11 | xargs -r rm -f --
    fi
}

migrate_schema() {
    log_info "Checking configuration schema migration..."

    if [ ! -f "$USER_CONFIG" ]; then
        if [ -f "$TEMPLATE_CONFIG" ]; then
            mkdir -p "$(dirname "$USER_CONFIG")"
            cp "$TEMPLATE_CONFIG" "$USER_CONFIG"
            log_success "Initialized configuration at $USER_CONFIG"
        fi
        return
    fi

    # Python-powered deep schema migration:
    # Recursively adds missing keys from template into user config while preserving existing values
    # Paths are passed in: under `python3 -` __file__ is "<stdin>", so the template used to be
    # looked up relative to the current directory and the migration silently skipped.
    if ! python3 - "$USER_CONFIG" "$TEMPLATE_CONFIG" << 'EOF'
import json
import os
import sys

user_cfg_path, template_cfg_path = sys.argv[1], sys.argv[2]

if not os.path.exists(template_cfg_path):
    print(f"[ERROR] Template config not found: {template_cfg_path}", file=sys.stderr)
    sys.exit(1)
if not os.path.exists(user_cfg_path):
    sys.exit(0)

with open(user_cfg_path, 'r', encoding='utf-8') as f:
    try:
        user_cfg = json.load(f)
    except Exception as e:
        print(f"[ERROR] Corrupted JSON in {user_cfg_path}: {e}", file=sys.stderr)
        sys.exit(1)

with open(template_cfg_path, 'r', encoding='utf-8') as f:
    template_cfg = json.load(f)

migrated_keys = []

def deep_merge(target, source, prefix=""):
    for key, val in source.items():
        full_key = f"{prefix}.{key}" if prefix else key
        if key not in target:
            target[key] = val
            migrated_keys.append(full_key)
        elif isinstance(val, dict) and isinstance(target.get(key), dict):
            deep_merge(target[key], val, full_key)

deep_merge(user_cfg, template_cfg)

if migrated_keys:
    # Atomic write back
    tmp_path = user_cfg_path + ".tmp"
    with open(tmp_path, 'w', encoding='utf-8') as f:
        json.dump(user_cfg, f, indent=2, ensure_ascii=False)
    os.replace(tmp_path, user_cfg_path)
    print(f"[SUCCESS] Migrated {len(migrated_keys)} new schema keys into user config: {', '.join(migrated_keys)}")
else:
    print("[INFO] Configuration schema is fully up-to-date. No migration required.")
EOF
    then
        log_error "Configuration migration failed."
        UPDATE_OK=false
    fi

    # Regenerate the per-user compositor config if install.sh generated it (non-default clone).
    local user_hypr="$HOME/.config/deloway/hyprland.conf"
    local marker="# Generated by DeloWay install.sh"
    if [ -f "$user_hypr" ] && [ ! -L "$user_hypr" ] && [[ "$(head -1 "$user_hypr")" == *"$marker"* ]]; then
        { echo "$marker for $DELOWAY_DIR — edits are overwritten by update.sh"
          sed "s|^\\\$delowayDir = .*|\\\$delowayDir = $DELOWAY_DIR|" "$DELOWAY_DIR/config/hyprland.conf"; } > "$user_hypr.tmp" \
            && mv "$user_hypr.tmp" "$user_hypr" && log_success "Regenerated $user_hypr"
    fi
}

sync_assets() {
    log_info "Syncing desktop assets and icon caches..."

    mkdir -p "$HOME/.local/share/icons/hicolor/scalable/apps" "$HOME/.local/share/applications"

    # Re-sync desktop folder icons
    if [ -d "$DELOWAY_DIR/assets/icons/desktop" ]; then
        cp -r "$DELOWAY_DIR/assets/icons/desktop/." "$HOME/.local/share/icons/hicolor/scalable/apps/" 2>/dev/null || true
    fi

    # Update caches
    if command -v gtk-update-icon-cache &>/dev/null; then
        gtk-update-icon-cache -f "$HOME/.local/share/icons/hicolor" 2>/dev/null || true
    fi
    if command -v update-desktop-database &>/dev/null; then
        update-desktop-database "$HOME/.local/share/applications" 2>/dev/null || true
    fi
}

reload_shell() {
    # Hot-reloading is banned (upstream crash during live QML reloads; the shell also sets
    # watchFiles: false). Detect the running instance and offer the clean restart instead.
    command -v quickshell &>/dev/null || return 0
    local qs_inst
    qs_inst=$(quickshell list --all 2>/dev/null | awk -v root="$DELOWAY_DIR/shell" \
        '/^Instance /{id=$2; sub(":", "", id)} /Config path:/ && index($0, root) {print id; exit}' || true)
    if [ -z "$qs_inst" ]; then
        log_info "The DeloWay shell is not running. Changes take effect on next login."
        return 0
    fi
    local restart_cmd="killall quickshell; sleep 1.5; hyprctl dispatch exec \"quickshell -p $DELOWAY_DIR/shell\""
    if [ "${1:-}" = "--restart" ]; then
        log_info "Restarting the shell cleanly (instance $qs_inst)..."
        bash -c "$restart_cmd"
        log_success "Shell restarted."
    else
        log_info "Shell instance $qs_inst is running. Apply the update with a clean restart:"
        echo "    $restart_cmd"
        echo "    (or re-run: ./update.sh --restart)"
    fi
}

# New versions can depend on packages or system setup an older install.sh never added
# (icon theme, fonts, hotspot tools, the Arabic locale). update.sh changes nothing on the
# system; it lists what is missing and points at install.sh, which is safe to re-run.
check_dependencies() {
    log_info "Checking dependencies..."
    local missing=() pkgs
    # The core package list is read from install.sh, so there is one list to maintain.
    pkgs=$(sed -n '/local core_tools=(/,/^    )/p' "$DELOWAY_DIR/install.sh" | grep -o '^ *"[^"]*"' | tr -d ' "')
    if command -v pacman &>/dev/null && [ -n "$pkgs" ]; then
        # pacman -T prints the dependencies that are not satisfied (exit 127 when some are)
        # shellcheck disable=SC2086
        mapfile -t missing < <(pacman -T $pkgs 2>/dev/null || true)
    fi
    [ -f /usr/share/icons/Reversal-black-dark/index.theme ] || [ -f "$HOME/.local/share/icons/Reversal-black-dark/index.theme" ] \
        || missing+=("deloway-icon-theme (packaging/deloway-icon-theme)")
    grep -qE '^ar_SA\.UTF-8[[:space:]]' /etc/locale.gen 2>/dev/null || missing+=("ar_SA.UTF-8 locale")
    if [ ${#missing[@]} -eq 0 ]; then
        log_success "All dependencies are installed."
    else
        log_warn "Missing since your last install: ${missing[*]}"
        log_warn "Install them with: (cd \"$DELOWAY_DIR\" && ./install.sh -y)  — it keeps your settings."
    fi
}

main() {
    print_header
    sync_git_repo
    backup_config
    migrate_schema
    sync_assets
    check_dependencies
    reload_shell "${1:-}"
    echo ""
    if [ "$UPDATE_OK" = true ]; then
        log_success "Deloway has been successfully updated and migrated!"
    else
        log_warn "Update finished with problems (see the messages above)."
        exit 1
    fi
}

main "$@"
