#!/usr/bin/env python3
"""DeloWay keyboard shortcuts. config/shortcuts.json is the one catalog of them.

    deloway-shortcuts.py gen              write config/hypr-binds.conf (Hyprland's defaults)
    deloway-shortcuts.py state  [OVR]     JSON for Settings → Shortcuts and the cheat sheet
    deloway-shortcuts.py apply  [OVR]     make Hyprland's live binds match the catalog + OVR

OVR is the user's changes as JSON, {action id: ["MODS|KEY", …]} ([] = no shortcut), as kept
in deloway.json → shortcuts. Fixed actions (workspace numbers, arrows, media keys, mouse)
ignore it.

apply reconciles instead of replaying: it reads the binds Hyprland has (hyprctl binds -j),
removes the catalog binds that are not wanted and adds the wanted ones that are missing.
Running it again changes nothing, so the shell can run it at start, after every change
and after every config reload (which brings the file's defaults back).
"""

import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CATALOG = REPO / "config" / "shortcuts.json"
GENERATED = REPO / "config" / "hypr-binds.conf"
RECORD_SUBMAP = "deloway-record"

MOD_BITS = {"SHIFT": 1, "CAPS": 2, "CTRL": 4, "CONTROL": 4, "ALT": 8, "MOD2": 16, "MOD3": 32,
            "SUPER": 64, "WIN": 64, "LOGO": 64, "MOD4": 64, "MOD5": 128}
MOD_ORDER = [("SUPER", 64), ("CTRL", 4), ("ALT", 8), ("SHIFT", 1)]


def load_catalog():
    return json.loads(CATALOG.read_text(encoding="utf-8"))


def expand(arg: str) -> str:
    return arg.replace("$delowayDir", str(REPO))


def modmask(mods: str) -> int:
    return sum(MOD_BITS.get(m.upper(), 0) for m in mods.replace("_", " ").split())


def mods_text(mask: int) -> str:
    return " ".join(name for name, bit in MOD_ORDER if mask & bit)


def bind_args(action, bind):
    """(dispatcher, arg) of one bind: a family (workspace 1…0) carries its own arg."""
    return action["dispatcher"], bind.get("arg", action.get("arg", ""))


def live_pair(action, bind):
    """(dispatcher, arg) as hyprctl binds -j reports it: a mouse bind (bindm) is the
    dispatcher "mouse" with the action as its argument."""
    disp, arg = bind_args(action, bind)
    return ("mouse", disp) if "m" in action.get("flags", "") else (disp, expand(arg))


def bind_line(action, bind, mods, key):
    """The argument list of a bind keyword: no trailing empty argument (bindm rejects it)."""
    disp, arg = bind_args(action, bind)
    return f"{mods}, {key}, {disp}" + (f", {arg}" if arg != "" else "")


def parse_combo(text: str):
    """"SUPER SHIFT|V" → {"mods": "SUPER SHIFT", "key": "V"}."""
    mods, _, key = text.partition("|")
    return {"mods": mods.strip(), "key": key.strip()}


def effective(catalog, overrides):
    """Each action with the binds it has now (override or default)."""
    out = []
    for action in catalog["actions"]:
        a = dict(action)
        own = overrides.get(action["id"]) if not action.get("fixed") else None
        if isinstance(own, list):
            a["binds"] = [parse_combo(c) for c in own if "|" in c]
            a["customized"] = True
        else:
            a["customized"] = False
        out.append(a)
    return out


def live_binds():
    try:
        out = subprocess.run(["hyprctl", "binds", "-j"], capture_output=True, text=True, timeout=5).stdout
        return json.loads(out or "[]")
    except (OSError, ValueError, subprocess.SubprocessError):
        return []


def key_id(mask, key):
    return (mask, key.lower())


# ── gen ──

def gen():
    cat = load_catalog()
    lines = ["# GENERATED by scripts/deloway-shortcuts.py gen from config/shortcuts.json — do not",
             "# edit by hand. Changes made in Settings → Shortcuts are applied at runtime on top.", ""]
    names = {g["id"]: g["en"] for g in cat["groups"]}
    group = None
    for a in cat["actions"]:
        if a["group"] != group:
            group = a["group"]
            lines += ["", f"# ── {names.get(group, group)} " + "─" * max(4, 70 - len(names.get(group, group)))]
        lines.append(f"# {a['en']}")
        for b in a["binds"]:
            lines.append(f"bind{a.get('flags', '')} = " + bind_line(a, b, b["mods"], b["key"]))
    lines += ["",
              "# Settings → Shortcuts records a new shortcut in this empty submap, so the keys",
              "# reach the shell instead of running their current action. The shell leaves it",
              "# itself; Super+Ctrl+Alt+Escape gets out if it ever cannot.",
              f"submap = {RECORD_SUBMAP}",
              "bind = SUPER CTRL ALT, Escape, submap, reset",
              "submap = reset", ""]
    GENERATED.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {GENERATED} ({sum(len(a['binds']) for a in cat['actions'])} binds)")


# ── state ──

def state(overrides):
    cat = load_catalog()
    actions = effective(cat, overrides)
    catalog_pairs = {live_pair(a, b) for a in cat["actions"] for b in a["binds"]}
    foreign = []
    for b in live_binds():
        if b.get("submap") or b.get("non_consuming") or not b.get("dispatcher"):
            continue
        if (b["dispatcher"], b.get("arg", "")) in catalog_pairs:
            continue
        foreign.append({"mods": mods_text(b.get("modmask", 0)), "key": b.get("key", ""),
                        "dispatcher": b["dispatcher"], "arg": b.get("arg", "")})
    print(json.dumps({"groups": cat["groups"], "actions": actions, "foreign": foreign}, ensure_ascii=False))


# ── apply ──

def hyprctl_keyword(*args):
    subprocess.run(["hyprctl", "keyword", *args], capture_output=True, timeout=5)


def apply(overrides):
    cat = load_catalog()
    wanted = {}          # (mask, key) → (keyword, keyword args, live dispatcher, live arg)
    for a in effective(cat, overrides):
        for b in a["binds"]:
            disp, arg = live_pair(a, b)
            wanted[key_id(modmask(b["mods"]), b["key"])] = (
                "bind" + a.get("flags", ""), expand(bind_line(a, b, b["mods"], b["key"])), disp, arg)
    catalog_pairs = {live_pair(a, b) for a in cat["actions"] for b in a["binds"]}

    have = {}
    for b in live_binds():
        if b.get("submap") or b.get("non_consuming"):
            continue
        if (b.get("dispatcher"), b.get("arg", "")) not in catalog_pairs:
            continue      # not ours (the user's own Hyprland binds): left alone
        have[key_id(b.get("modmask", 0), b.get("key", ""))] = (b.get("dispatcher"), b.get("arg", ""), b)

    removed = added = 0
    for kid, (disp, arg, b) in have.items():
        w = wanted.get(kid)
        if w is None or (w[2], w[3]) != (disp, arg):
            hyprctl_keyword("unbind", f"{mods_text(kid[0])},{b.get('key', '')}")
            removed += 1
            have[kid] = (None, None, b)
    for kid, (kw, line, disp, arg) in wanted.items():
        h = have.get(kid)
        if h is None or (h[0], h[1]) != (disp, arg):
            hyprctl_keyword(kw, line)
            added += 1
    print(json.dumps({"ok": True, "removed": removed, "added": added}))


def read_overrides(argv):
    if len(argv) < 3 or not argv[2].strip():
        return {}
    try:
        data = json.loads(argv[2])
        return data if isinstance(data, dict) else {}
    except ValueError:
        return {}


def main(argv):
    cmd = argv[1] if len(argv) > 1 else ""
    if cmd == "gen":
        gen()
    elif cmd == "state":
        state(read_overrides(argv))
    elif cmd == "apply":
        apply(read_overrides(argv))
    else:
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
