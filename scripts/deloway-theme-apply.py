def build_settings_ini(gtk_theme: str, icon_theme: str, cursor_theme: str, font_name: str, is_dark: bool) -> str:
    """Generate clean, unified settings.ini for GTK 3 and GTK 4."""
    prefer_dark_val = "1" if is_dark else "0"
    return f"""[Settings]
gtk-theme-name={gtk_theme}
gtk-icon-theme-name={icon_theme}
gtk-font-name={font_name}
gtk-cursor-theme-name={cursor_theme}
gtk-cursor-theme-size=24
gtk-application-prefer-dark-theme={prefer_dark_val}
gtk-xft-antialias=1
gtk-xft-hinting=1
gtk-xft-hintstyle=hintslight
gtk-xft-rgba=rgb
"""


def main():
    parser = argparse.ArgumentParser(description="DeloWay Dynamic System Theme Engine")
    parser.add_argument("--dry-run", action="store_true", help="Preview changes without writing files or setting gsettings")
    parser.add_argument("--theme-json", type=str, default="", help="Path to theme.json (defaults to project theme.json)")
    parser.add_argument("--mode", type=str, default="", choices=["dark", "light"], help="Force theme mode")
    parser.add_argument("--accent", type=str, default="", help="Force accent color hex")
    args = parser.parse_args()

    project_dir = Path(__file__).resolve().parent.parent
    theme_json_path = Path(args.theme_json) if args.theme_json else project_dir / "shell" / "theme" / "theme.json"

    # Default fallback values
    mode = "dark"
    accent = "#0ea5e9"
    colors = {}

    if theme_json_path.exists():
        try:
            with open(theme_json_path, "r", encoding="utf-8") as f:
                data = json.load(f)
            mode = args.mode or data.get("mode", "dark")
            accent = args.accent or data.get("accent") or (data.get("colors", {}).get("accent", "#0ea5e9"))
            if mode in data and isinstance(data[mode], dict):
                colors = data[mode]
            elif "colors" in data and isinstance(data["colors"], dict):
                colors = data["colors"]
        except Exception as e:
            print(f"[deloway-theme] Warning reading {theme_json_path}: {e}", file=sys.stderr)

    if args.mode:
        mode = args.mode
    if args.accent:
        accent = args.accent

    is_dark = (mode == "dark")
    gtk_theme = "adw-gtk3-dark" if is_dark else "adw-gtk3"
    color_scheme = "prefer-dark" if is_dark else "prefer-light"

    # 1. Read authoritative system settings from gsettings
    icon_theme = get_gsettings_value("icon-theme") or "Reversal-dark"
    cursor_theme = get_gsettings_value("cursor-theme") or "default"
    font_name = get_gsettings_value("font-name") or "Google Sans Flex Medium 11 @opsz=11,wght=500"

    print(f"[deloway-theme] Mode: {mode} | Accent: {accent} | GTK Theme: {gtk_theme}")
    print(f"[deloway-theme] System: icons='{icon_theme}' cursors='{cursor_theme}' font='{font_name}'")

    # 2. Build CSS and INI contents
    gtk_css_content = build_gtk_css(mode, colors, accent)
    settings_ini_content = build_settings_ini(gtk_theme, icon_theme, cursor_theme, font_name, is_dark)

    # 3. Target config directories (support XDG_CONFIG_HOME)
    config_home = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    gtk3_dir = config_home / "gtk-3.0"
    gtk4_dir = config_home / "gtk-4.0"

    # 4. Atomic write to GTK 3.0 and GTK 4.0
    atomic_write_if_changed(gtk3_dir / "gtk.css", gtk_css_content, dry_run=args.dry_run)
    atomic_write_if_changed(gtk4_dir / "gtk.css", gtk_css_content, dry_run=args.dry_run)
    atomic_write_if_changed(gtk3_dir / "settings.ini", settings_ini_content, dry_run=args.dry_run)
    atomic_write_if_changed(gtk4_dir / "settings.ini", settings_ini_content, dry_run=args.dry_run)

    # 5. Apply gsettings
    set_gsettings_value("color-scheme", color_scheme, dry_run=args.dry_run)
    set_gsettings_value("gtk-theme", gtk_theme, dry_run=args.dry_run)

    print("[deloway-theme] Completed successfully.")


if __name__ == "__main__":
    main()
