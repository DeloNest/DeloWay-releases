#!/usr/bin/env python3
"""Generate config/hypr-startmenu.conf — Super-tap detection for the Start menu.

Hyprland can't distinguish "Super tapped alone" from "Super used in a combo", and
`catchall` binds are only allowed inside submaps. So we emit one transparent,
non-consuming interrupt bind per physical keycode (layout-independent: works for
us + ara alike) for every Super modifier combination, plus mouse buttons/wheel.
The shell arms on Super press, disarms on any interrupt, toggles on release.

Regenerate:  python3 scripts/gen-startmenu-binds.py
"""
import pathlib

MODIFIER_CODES = {37, 50, 62, 64, 66, 105, 108, 133, 134, 135}   # Ctrl/Shift/Alt/Caps/Super/Menu
KEYCODES = [c for c in range(9, 256) if c not in MODIFIER_CODES]
MOD_SETS = ["SUPER", "SUPER SHIFT", "SUPER CTRL", "SUPER ALT"]
MOUSE = ["mouse:272", "mouse:273", "mouse:274", "mouse:275", "mouse:276",
         "mouse_up", "mouse_down", "mouse_left", "mouse_right"]
TARGET = "global, quickshell:startMenuInterrupt"

lines = [
    "# GENERATED by scripts/gen-startmenu-binds.py — do not edit by hand.",
    "# Super tap → Start menu; any other input while Super is held cancels it.",
    "",
    "# Arm on Super press (i: ignore mods — Super isn't in the mod state yet at its own press)",
    "bindid = SUPER, SUPER_L, Start menu, global, quickshell:startMenuSuper",
    "bindid = SUPER, SUPER_R, Start menu, global, quickshell:startMenuSuper",
    "",
    "# Modifiers pressed after Super (Super+Shift+…, Super+Ctrl+…, Super+Alt+…) cancel too",
]
for code in (50, 62, 37, 105, 64, 108):
    lines.append(f"bindtn = SUPER, code:{code}, {TARGET}")
lines.append("")
for mods in MOD_SETS:
    lines.append(f"# {mods} + any key / mouse → cancel pending tap")
    for code in KEYCODES:
        lines.append(f"bindtn = {mods}, code:{code}, {TARGET}")
    for m in MOUSE:
        lines.append(f"bindtn = {mods}, {m}, {TARGET}")
    lines.append("")

out = pathlib.Path(__file__).resolve().parent.parent / "config" / "hypr-startmenu.conf"
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({sum(1 for l in lines if l.startswith('bind'))} binds)")
